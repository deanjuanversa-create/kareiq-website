const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
// web addresses in an answer become links
const linkify = (s) => esc(s).replace(/https?:\/\/[^\s<]*[^\s<.,]/g, (u) => `<a href="${u}" target="_blank" rel="noopener">${u}</a>`);
const answer = (a) => a.map((x) => (typeof x === 'string'
  ? `<p>${linkify(x)}</p>`
  : `<ul>${x.list.map((li) => `<li><span>${li.b ? `<b>${esc(li.b)}</b> ` : ''}${linkify(li.t)}</span></li>`).join('')}</ul>`)).join('');

// A group's anchor on the FAQ page (#faq-about-kareiq): used by the topic links
const slug = (t) => 'faq-' + String(t).toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

// The question groups of one website as native <details> accordions (keyboard and screen-reader
// friendly with no script). The page wraps them in its own section and heading.
function faqGroups(site) {
  return FAQ[site].groups.map((g) => `<div class="faq-group" id="${slug(g.title)}">
        <h2 class="faq-group-title">${esc(g.title)}</h2>${g.desc ? `<p class="faq-group-desc">${esc(g.desc)}</p>` : ''}
        ${g.items.map((it) => `<details class="faq"><summary>${esc(it.q)}</summary><div class="faq-body">${answer(it.a)}</div></details>`).join('\n        ')}
      </div>`).join('\n      ');
}

// The body of a website's FAQ page (each website has its own page, 2 Nov 2026): a search box and
// topic links above the questions, and a note when a search finds nothing. The search box stays
// hidden until the page script (faq-page.js) is running; the topic links work without it.
//   contact: the address of the site's contact or enquiry section, for "ask us" links
function faqPageBody(site, contact) {
  const F = FAQ[site];
  const n = F.groups.reduce((t, g) => t + g.items.length, 0);
  return `<div class="faq-layout">
      <div class="faq-tools" data-faq>
        <div class="faq-search" hidden>
          <svg viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" aria-hidden="true"><circle cx="11" cy="11" r="7"/><path d="m20 20-3.6-3.6"/></svg>
          <input type="search" id="faq-q" placeholder="Search ${n} questions" aria-label="Search the frequently asked questions" autocomplete="off">
          <button type="button" class="faq-clear" aria-label="Clear the search" hidden>&times;</button>
        </div>
        <nav class="faq-topics" aria-label="Question topics">
          ${F.groups.map((g) => `<a href="#${slug(g.title)}">${esc(g.title)}<small>${g.items.length}</small></a>`).join('\n          ')}
        </nav>
        <p class="faq-count" role="status" aria-live="polite"></p>
      </div>
      <div class="faq-main">
      <div class="faqs">
      ${faqGroups(site)}
      </div>
      <div class="faq-empty" hidden>
        <p><b>No questions match your search.</b></p>
        <p>Try another word, or <a href="${contact}">ask our team directly</a>.</p>
      </div>
      </div>
      </div>`;
}

